import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import SourceWorkspace from '../apps/playground/src/components/views/SourceWorkspace.jsx';
import { openPresentation } from '@stagecraft/source';
afterEach(cleanup);
const texts = slide => slide.objects.flatMap(o => o.text?.paragraphs.flatMap(p => p.runs.map(r => r.text)) ?? []).join('');
const editNumber = (label, value) => { const input = screen.getByLabelText(label); fireEvent.change(input, { target: { value } }); fireEvent.blur(input); };
const insert = name => { fireEvent.click(screen.getByRole('tab', { name: 'Insert' })); fireEvent.click(screen.getByRole('button', { name })); };
describe('visual authoring workflow in Chromium', () => {
  it.each(['pptx', 'odp'])('creates, arranges and exports a new %s presentation', async format => {
    const save = vi.fn(); render(<SourceWorkspace save={save} />);
    fireEvent.click(screen.getByRole('button', { name: `New ${format.toUpperCase()}` }));
    await screen.findByRole('region', { name: 'Presentation editor' });
    insert('Text box');
    fireEvent.change(screen.getByLabelText('Text run 1'), { target: { value: 'Deck title' } });
    fireEvent.change(screen.getByLabelText('Bold run 1'), { target: { value: 'true' } });
    editNumber('Font size run 1', '32');
    editNumber('X (pt)', '64'); editNumber('Width (pt)', '300');
    insert('Rectangle');
    fireEvent.change(screen.getByLabelText('Fill'), { target: { value: '#cc5500' } });
    insert('Ellipse');
    fireEvent.click(screen.getByRole('tab', { name: 'Home' }));
    fireEvent.click(screen.getByRole('button', { name: 'Delete object' }));
    const canvas = screen.getByRole('region', { name: 'Slide canvas' });
    fireEvent.click(canvas.querySelector('[data-object-id]'));
    fireEvent.click(screen.getByRole('button', { name: 'Bring forward' }));
    fireEvent.click(screen.getByRole('button', { name: 'Add slide' }));
    insert('Text box'); fireEvent.change(screen.getByLabelText('Text run 1'), { target: { value: 'Second slide' } });
    fireEvent.click(screen.getByRole('button', { name: 'Move slide up' }));
    fireEvent.click(screen.getByRole('button', { name: 'Export' }));
    await waitFor(() => expect(save).toHaveBeenCalledTimes(1));
    const source = await openPresentation(save.mock.calls[0][0].bytes, { format });
    expect(source.document.slides).toHaveLength(2);
    expect(texts(source.document.slides[0])).toBe('Second slide');
    expect(texts(source.document.slides[1])).toBe('Deck title');
    expect(source.document.slides[1].objects).toHaveLength(2);
    const text = source.document.slides[1].objects.find(o => o.text);
    expect(text.geometry.x).toBe(64 * 12700);
    expect(text.geometry.width).toBe(300 * 12700);
    const run = text.text.paragraphs[0].runs[0];
    if (format === 'pptx') expect(run.style).toMatchObject({ b: '1', sz: '3200' });
    else expect(run.extensions.odpAppearance).toMatchObject({ bold: true, fontSize: 32 });
    source.dispose();
  });
});
